  'permission denied for table r10_new_api_probe','GRANT SELECT no habilita INSERT');
reset role;
set local role anon;
select throws_ok($$select * from public.r10_new_api_probe$$,'42501',
  'permission denied for table r10_new_api_probe','anon permanece bloqueado despues del GRANT autenticado');
reset role;
