  where n.nspname='public' and c.relkind in ('r','p') and not c.relrowsecurity),'RLS en todas las tablas');
select results_eq(
  $$select c.relname::text from pg_class c join pg_namespace n on n.oid=c.relnamespace
    where n.nspname='public' and c.relkind in ('r','p')
      and has_table_privilege('authenticated',c.oid,'SELECT') order by c.relname$$,
  $$select name from (values ('campaigns'),('center_campaigns'),('center_contacts'),
    ('center_creation_audit'),('center_state'),('center_state_audit'),('centers'),
    ('contact_event_opportunities'),('contact_events'),('export_audit'),('operator_audit'),
    ('operator_presence'),('opportunity_audit'),('travel_opportunities')) v(name) order by name$$,
  'Las 14 lecturas de authenticated dependen de permisos explicitos');
select ok(not exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind in ('r','p','v','m')
  and has_table_privilege('anon',c.oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER,MAINTAIN')),
  'anon no tiene privilegios sobre tablas ni vistas del CRM');
select ok(not exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
