  $$select c.relname::text from pg_class c join pg_namespace n on n.oid=c.relnamespace
    where n.nspname='public' and c.relkind='v' and 'security_invoker=true'=any(c.reloptions)
    and has_table_privilege('authenticated',c.oid,'SELECT') order by c.relname$$,
  $$values ('crm_centers'::text),('crm_export_centers'::text)$$,
  'Las dos vistas conservan lectura y security_invoker');
select ok(not exists(select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public' and p.prosecdef and has_function_privilege('anon',p.oid,'EXECUTE')),
  'Ninguna funcion SECURITY DEFINER publica es ejecutable por anon');
