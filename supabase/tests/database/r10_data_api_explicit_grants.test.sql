grant select on public.r10_new_api_probe to authenticated;
set local role authenticated;
select results_eq($$select id from public.r10_new_api_probe order by id$$,array[1::bigint],
  'GRANT explicito permite leer solo la fila propia');
select results_eq($$select count(*) from public.r10_new_api_probe where id=2$$,array[0::bigint],
  'El GRANT no permite cruzar filas entre usuarios');
