-- Simulate the transition on existing objects without changing their grants.
alter default privileges for role postgres in schema public
  grant select,insert,update,delete on tables to anon,authenticated,service_role;
alter default privileges for role postgres in schema public
  grant usage,select on sequences to anon,authenticated,service_role;
create table public.r10_existing_api_probe(id bigint generated by default as identity);
select ok(has_table_privilege('authenticated','public.r10_existing_api_probe','SELECT'),'Control: tabla antigua recibe grant automatico');
create temporary table r10_acl_snapshot as
  select c.oid,c.relacl::text as acl from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind in ('r','p','v','m','S');
alter default privileges for role postgres in schema public
  revoke select,insert,update,delete on tables from anon,authenticated,service_role;
alter default privileges for role postgres in schema public
  revoke usage,select on sequences from anon,authenticated,service_role;
select ok(not exists(select 1 from r10_acl_snapshot s join pg_class c on c.oid=s.oid
  where s.acl is distinct from c.relacl::text),'Cambio de defaults no altera ningun permiso existente');
select ok(has_table_privilege('authenticated','public.r10_existing_api_probe','SELECT'),'Tabla anterior sigue accesible');
create table public.r10_new_api_probe(id bigint generated by default as identity primary key, owner_id uuid not null);
alter table public.r10_new_api_probe enable row level security;
create policy r10_probe_owner on public.r10_new_api_probe for select to authenticated
  using ((select auth.uid())=owner_id);
select ok(not exists(select 1 from unnest(array['anon','authenticated','service_role']) r(role_name)
  where has_table_privilege(role_name,'public.r10_new_api_probe','SELECT,INSERT,UPDATE,DELETE')),
  'Una tabla nueva no recibe acceso CRUD automatico para ningun rol API');
select ok(not exists(select 1 from unnest(array['anon','authenticated','service_role']) r(role_name)
  where has_sequence_privilege(role_name,'public.r10_new_api_probe_id_seq','USAGE,SELECT')),
  'Una secuencia nueva no recibe USAGE/SELECT automaticos');
insert into public.r10_new_api_probe(owner_id) values
  ('30000000-0000-4000-8000-000000000001'),('30000000-0000-4000-8000-000000000002');
set local role authenticated;
select set_config('request.jwt.claims','{"sub":"30000000-0000-4000-8000-000000000001","role":"authenticated"}',true);
select throws_ok($$select * from public.r10_new_api_probe$$,'42501',
  'permission denied for table r10_new_api_probe','RLS sola no sustituye al GRANT');
