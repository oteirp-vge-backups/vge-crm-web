#!/usr/bin/env bash
# TEST ONLY. No remote credentials, cloud project, production data or deployment.
set -Eeuo pipefail
{ set +x; } 2>/dev/null
umask 077
BASE=871051cdf68178c349b3b490ed2727f38ad540e2
[[ "${R10_ISOLATED_CI:-}" == YES && "${GITHUB_ACTIONS:-}" == true ]] || {
  echo 'REFUSED: disposable GitHub Actions runner required.' >&2; exit 1;
}
for name in SUPABASE_ACCESS_TOKEN SUPABASE_DB_PASSWORD SUPABASE_DB_URL TARGET_DB_URL DATABASE_URL AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY RESEND_API_KEY; do
  [[ ! -v "$name" ]] || { echo "REFUSED: unexpected credential variable $name" >&2; exit 1; }
done
cd "$(git rev-parse --show-toplevel)"
[[ ! -e supabase/.temp/project-ref ]] || { echo 'REFUSED: linked project'; exit 1; }
grep -qx 'project_id = "vge-crm-r10-quality-gate"' supabase/config.toml
# These sources are immutable in this audit, including all existing workflows.
while IFS= read -r path; do
  case "$path" in
    .github/workflows/r10-data-api-explicit-grants.yml|scripts/r10-data-api-isolated.sh|scripts/r10-data-api-smoke.py|supabase/tests/database/r10_data_api_explicit_grants.test.sql|docs/R10_DATA_API_20261030.md) ;;
    *) echo "REFUSED: out-of-scope change: $path" >&2; exit 1 ;;
  esac
done < <(git diff --name-only "$BASE" HEAD)
git cat-file -e "${BASE}^{commit}"
git merge-base --is-ancestor "$BASE" HEAD
(cd supabase/baseline && sha256sum --check current-schema.sql.sha256)
python3 -m py_compile scripts/r10-data-api-smoke.py
for cmd in start status test stop; do supabase "$cmd" --help >/dev/null; done
supabase test db --help >/dev/null
MIGRATIONS_DIR="$(mktemp -d "${RUNNER_TEMP}/r10-data-api-migrations.XXXXXX")"
STATUS_FILE="$(mktemp "${RUNNER_TEMP}/r10-local-status.XXXXXX")"
cleanup() {
  supabase stop --no-backup >/dev/null 2>&1 || true
  rm -f -- "$STATUS_FILE"
}
trap cleanup EXIT
# The historical sources are partial: restore the checked baseline, never db reset.
mv supabase/migrations "$MIGRATIONS_DIR/source"
mkdir supabase/migrations
supabase start >/dev/null
local_psql() {
  env -i PATH="$PATH" HOME="$HOME" PGPASSWORD=postgres PGSSLMODE=disable \
    psql -X --host=127.0.0.1 --port=54322 --username=postgres --dbname=postgres \
    --set=ON_ERROR_STOP=1 "$@"
}
# Fail closed before any schema changes: the local public schema must be empty.
local_psql --command="DO \$\$ BEGIN IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relkind IN ('r','p')) THEN RAISE EXCEPTION 'LOCAL_TARGET_NOT_EMPTY'; END IF; END \$\$;"
# Exact table/sequence opt-in described by Supabase's 2026-04-28 announcement.
local_psql <<'SQL'
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  REVOKE SELECT, INSERT, UPDATE, DELETE ON TABLES FROM anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  REVOKE USAGE, SELECT ON SEQUENCES FROM anon, authenticated, service_role;
BEGIN;
CREATE TABLE public.r10_pre_restore_probe (id bigint GENERATED BY DEFAULT AS IDENTITY);
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM unnest(ARRAY['anon','authenticated','service_role']) r(role_name)
    WHERE has_table_privilege(role_name,'public.r10_pre_restore_probe','SELECT,INSERT,UPDATE,DELETE')
       OR has_sequence_privilege(role_name,'public.r10_pre_restore_probe_id_seq','USAGE,SELECT'))
  THEN RAISE EXCEPTION 'DEFAULT_GRANTS_STILL_ACTIVE'; END IF;
END $$;
SELECT 'INFO: legacy admin defaults before restore preparation=' ||
  has_table_privilege('anon','public.r10_pre_restore_probe','TRUNCATE,REFERENCES,TRIGGER,MAINTAIN')::text;
ROLLBACK;
SQL
# Mirror the existing restore_from_local.sh preparation, not a new CRM migration.
# Source: backup-automation@95838ed7411ecbc14d2e4e8d6e480b34adae8761.
# The official change removes CRUD defaults, not inherited administrative defaults.
# Without the existing preparation a dump can inherit extra target privileges.
local_psql --command='ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon, authenticated'
local_psql --file=supabase/baseline/current-schema.sql >/dev/null
for migration in \
  20260826061114_reduce_security_definer_surface.sql \
  20260828072643_normalize_center_communities.sql \
  20260913071737_align_statistics_with_portfolio_status.sql; do
  local_psql --file="$MIGRATIONS_DIR/source/$migration" >/dev/null
done
local_psql --file=supabase/tests/fixtures/r10_agenda_email_cron_fixture.sql >/dev/null
for migration in \
  20260915103838_disable_agenda_email_notifications.sql \
  20260915113006_resolve_general_followup_from_linked_contact.sql \
  20260916101500_normalize_center_provinces.sql \
  20260916193916_add_internal_notes_history.sql \
  20261013102327_enable_center_details_editing.sql; do
  local_psql --file="$MIGRATIONS_DIR/source/$migration" >/dev/null
done
# Fail rather than leave a locally reconstructed task capable of sending emails.
local_psql --command="DO \$\$ BEGIN IF EXISTS (SELECT 1 FROM cron.job WHERE active AND command NOT IN ('select 1','select 2','select 3')) THEN RAISE EXCEPTION 'NON_INERT_CRON_IN_TEST'; END IF; END \$\$;"
supabase test db \
  supabase/tests/database/r10_role_permissions.test.sql \
  supabase/tests/database/r10_phase7_security_definer.test.sql \
  supabase/tests/database/r10_community_normalization.test.sql \
  supabase/tests/r10_statistics_portfolio_alignment_test.sql \
  supabase/tests/database/r10_disable_agenda_email_notifications.test.sql \
  supabase/tests/database/r10_agenda_scope_resolution.test.sql \
  supabase/tests/database/r10_province_normalization.test.sql \
  supabase/tests/database/r10_internal_notes.test.sql \
  supabase/tests/database/r10_center_details.test.sql \
  supabase/tests/database/r10_data_api_explicit_grants.test.sql
# This file contains ONLY keys for the newly started local stack; never upload it.
supabase status -o json > "$STATUS_FILE"
python3 scripts/r10-data-api-smoke.py "$STATUS_FILE"
echo 'PASS: isolated reconstruction, role contracts, default-grant transition and local HTTP API.'
